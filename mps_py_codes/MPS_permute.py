    # print("Before adjustment:")
    # print("lx:", lx)
    # print("ly:", ly)
    # print("lz:", lz)

    # Find the longest array length
    max_len = max(len(lx), len(ly), len(lz))

    # Adjust lx if it is shorter
    if len(lx) < max_len:
        diff = max_len - len(lx)
        lx = [-1] * diff + lx

    # Adjust ly if it is shorter
    if len(ly) < max_len:
        diff = max_len - len(ly)
        ly = [-1] * diff + ly

    # Adjust lz if it is shorter
    if len(lz) < max_len:
        diff = max_len - len(lz)
        lz = [-1] * diff + lz

